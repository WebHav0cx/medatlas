import { z } from "zod";
const str = z.string(),
  strings = z.array(str);
const roles = z.enum([
  "doctor",
  "nurse",
  "records",
  "admin",
  "lab-reception",
  "lab-scientist",
  "lab-reviewer",
  "lab-admin",
]);
const requestStatus = z.enum([
  "Draft",
  "Submitted",
  "Under Review",
  "Approved",
  "Declined",
  "Fulfilled",
  "Cancelled",
]);
const patientRequestStatus = z.enum([
  "Submitted",
  "Under Review",
  "Additional Information Required",
  "Completed",
  "Declined",
  "Cancelled",
]);
const diagnosticStatus = z.enum([
  "Submitted",
  "Acknowledged",
  "Incomplete",
  "Assigned",
  "Specimen Collected",
  "Processing",
  "Awaiting Review",
  "Correction Required",
  "Approved",
  "Released",
  "Completed",
  "Cancelled",
]);
const priority = z.enum(["Routine", "Urgent"]);
const organisationType = z.enum([
  "Hospital",
  "Clinic",
  "Laboratory / Diagnostic Centre",
]);
const patientAccount = z.object({
  id: str,
  patientId: str.optional(),
  fullName: str,
  email: str,
  phone: str,
  dob: str,
  status: z.enum(["Active", "Inactive"]),
  createdAt: str,
  preferences: z.object({
    email: z.boolean(),
    sms: z.boolean(),
    sharing: z.boolean(),
    records: z.boolean(),
  }),
});
export const workflowStateSchema = z.object({
  currentAccountId: str,
  currentPatientAccountId: str,
  facilityProfiles: z
    .record(
      z.string(),
      z.object({
        name: str,
        type: str,
        address: str,
        phone: str,
        email: str,
        departments: strings,
      }),
    )
    .optional(),
  patients: z.array(
    z.object({
      id: str,
      medAtlasId: str,
      firstName: str,
      lastName: str,
      dob: str,
      sex: str,
      phone: str,
      localId: str,
      verification: z.enum(["Verified", "Pending"]),
      assignedStaff: strings,
      sourceFacilities: strings,
    }),
  ),
  encounters: z.array(
    z.object({
      id: str,
      patientId: str,
      type: str,
      facility: str,
      date: str,
      recordCategories: strings,
    }),
  ),
  documents: z.array(
    z.object({
      id: str,
      patientId: str,
      title: str,
      category: str,
      sourceFacility: str,
      date: str,
      access: z.enum(["Approved", "Limited", "Access denied"]),
      patientAccess: z.enum(["Available", "Restricted", "Pending"]).optional(),
      author: str.optional(),
      eventId: str.optional(),
      requestId: str.optional(),
    }),
  ),
  requests: z.array(
    z.object({
      id: str,
      patientId: str,
      requester: str,
      sourceFacility: str,
      category: str,
      purpose: str,
      authorisation: str,
      priority,
      status: requestStatus,
      createdAt: str,
      history: z.array(
        z.object({
          status: requestStatus,
          at: str,
          actor: str,
          note: str.optional(),
        }),
      ),
    }),
  ),
  referrals: z.array(
    z.object({
      id: str,
      patientId: str,
      destination: str,
      reason: str,
      context: str,
      attachments: strings,
      status: z.enum([
        "Draft",
        "Submitted",
        "Acknowledged",
        "In Progress",
        "Completed",
        "Cancelled",
      ]),
      createdAt: str,
    }),
  ),
  identityCases: z.array(
    z.object({
      id: str,
      patientAId: str,
      patientBId: str,
      reasons: strings,
      matchingEvidence: strings,
      conflictingEvidence: strings,
      documents: strings,
      status: z.enum([
        "Pending Review",
        "Verification Required",
        "Under Review",
        "Resolved as Distinct",
        "Merge Approved",
      ]),
      notes: strings,
      decisions: z.array(
        z.object({
          action: str,
          actor: str,
          at: str,
          note: str,
        }),
      ),
    }),
  ),
  staff: z.array(
    z.object({
      id: str,
      name: str,
      role: roles,
      title: str,
      department: str,
      email: str,
      status: z.enum(["Active", "Pending Activation", "Deactivated"]),
      lastActive: str,
      organisationId: str.optional(),
    }),
  ),
  tasks: z.array(
    z.object({
      id: str,
      patientId: str,
      title: str,
      assignedTo: str,
      assignedBy: str,
      due: str,
      priority: z.enum(["Routine", "High"]),
      status: z.enum(["Assigned", "Pending", "Completed", "Escalated"]),
    }),
  ),
  audit: z.array(
    z.object({
      id: str,
      at: str,
      actor: str,
      role: str,
      action: str,
      resource: str,
      outcome: str,
      detail: str,
    }),
  ),
  organisations: z.array(
    z.object({
      id: str,
      name: str,
      type: organisationType,
      location: str,
      status: z.enum(["Active", "Pending Review"]),
    }),
  ),
  diagnosticRequests: z.array(
    z.object({
      id: str,
      patientId: str,
      requestingFacility: str,
      destination: str,
      requestingClinician: str,
      tests: strings,
      priority,
      purpose: str,
      submittedAt: str,
      status: diagnosticStatus,
      assignedScientistId: str.optional(),
      history: z.array(
        z.object({
          status: diagnosticStatus,
          at: str,
          actor: str,
          note: str.optional(),
        }),
      ),
    }),
  ),
  specimens: z.array(
    z.object({
      id: str,
      requestId: str,
      patientId: str,
      sampleType: str,
      collectedAt: str,
      collector: str,
      status: z.enum([
        "Awaiting Collection",
        "Collected",
        "Received",
        "Processing",
        "Processing Completed",
        "Rejected",
        "Recollection Required",
      ]),
      assignedTo: str,
      rejectionReason: str.optional(),
    }),
  ),
  labResults: z.array(
    z.object({
      id: str,
      requestId: str,
      patientId: str,
      values: z.array(
        z.object({
          test: str,
          value: str,
          unit: str,
          reference: str,
          flag: z.enum(["Normal", "High", "Low"]),
        }),
      ),
      comments: str,
      reportTitle: str,
      status: z.enum([
        "Draft",
        "Submitted for Review",
        "Correction Required",
        "Approved",
        "Released",
      ]),
      scientistId: str,
      reviewerId: str.optional(),
      updatedAt: str,
    }),
  ),
  exchanges: z.array(
    z.object({
      id: str,
      requestId: str,
      resultId: str,
      patientId: str,
      sender: str,
      recipient: str,
      documentType: str,
      status: z.enum(["Prepared", "Released", "Received", "Failed"]),
      receiptStatus: z.enum(["Pending", "Acknowledged"]),
      at: str,
      responsibleUser: str,
    }),
  ),
  invitations: z.array(
    z.object({
      code: str,
      organisationId: str,
      email: str,
      role: roles,
      department: str,
      status: z.enum(["Pending", "Accepted", "Revoked"]),
    }),
  ),
  organisationApplications: z.array(
    z.object({
      id: str,
      registeredName: str,
      displayName: str,
      type: organisationType,
      state: str,
      lga: str,
      address: str,
      email: str,
      phone: str,
      licence: str,
      authority: str,
      administratorName: str,
      administratorEmail: str,
      status: z.enum(["Pending Review", "Approved", "Declined"]),
    }),
  ),
  patientAccounts: z.array(patientAccount),
  patientLinks: z.array(
    z.object({
      id: str,
      accountId: str,
      patientId: str.optional(),
      facility: str,
      method: z.enum(["Linking Code", "Facility Invitation", "Review Request"]),
      status: z.enum([
        "Not Linked",
        "Pending Verification",
        "Additional Information Required",
        "Linked",
        "Declined",
        "Under Review",
      ]),
      submittedAt: str,
      updatedAt: str,
      note: str,
    }),
  ),
  sharingPermissions: z.array(
    z.object({
      id: str,
      accountId: str,
      patientId: str,
      requestId: str,
      requestingOrganisation: str,
      requestingProfessional: str,
      sourceFacility: str,
      recordCategory: str,
      purpose: str,
      scope: str,
      duration: str,
      status: z.enum([
        "Pending Decision",
        "Active",
        "Declined",
        "Withdrawn",
        "Expired",
      ]),
      createdAt: str,
      decidedAt: str.optional(),
    }),
  ),
  patientRequests: z.array(
    z.object({
      id: str,
      accountId: str,
      patientId: str.optional(),
      type: z.enum([
        "Access Existing Records",
        "Record Linking",
        "Correction Review",
        "Copy of Record",
      ]),
      facility: str,
      documentId: str.optional(),
      note: str,
      status: patientRequestStatus,
      submittedAt: str,
      updatedAt: str,
      history: z.array(
        z.object({
          status: patientRequestStatus,
          at: str,
          actor: str,
          note: str,
        }),
      ),
    }),
  ),
  patientNotifications: z.array(
    z.object({
      id: str,
      accountId: str,
      type: z.enum([
        "Record Available",
        "Sharing Request",
        "Sharing Expiring",
        "Record Link",
        "Request Update",
      ]),
      title: str,
      message: str,
      at: str,
      read: z.boolean(),
      href: str,
      relatedId: str,
    }),
  ),
  facility: z.object({
    name: str,
    type: str,
    address: str,
    phone: str,
    email: str,
    departments: strings,
  }),
});
